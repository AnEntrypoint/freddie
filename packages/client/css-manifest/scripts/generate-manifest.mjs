#!/usr/bin/env node
// Regenerates src/manifest.js from the repo's git-tracked plain CSS files
// (excluding lib/ build output). Run from the repo root: node
// packages/client/css-manifest/scripts/generate-manifest.mjs
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = fileURLToPath(new URL('../../../../', import.meta.url))
const outFile = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'manifest.js')

const output = execFileSync('git', ['ls-files', '*.css'], { cwd: repoRoot, encoding: 'utf8' })
const paths = output
  .split('\n')
  .map(line => line.trim())
  .filter(line => line !== '' && !line.includes('/lib/'))
  .sort()

const entries = paths.map(path => ({
  id: path.replace(/^packages\//, '').replace(/\.css$/, '').replace(/[/.]/g, '-'),
  path,
}))

const seen = new Map()
for (const entry of entries) {
  const prior = seen.get(entry.id)
  if (prior !== undefined) {
    throw new Error(`css-manifest: id collision "${entry.id}" between "${prior}" and "${entry.path}"`)
  }
  seen.set(entry.id, entry.path)
}

const lines = entries.map(entry => `  { id: ${JSON.stringify(entry.id)}, path: ${JSON.stringify(entry.path)} },`).join('\n')
const body = `// Generated by scripts/generate-manifest.mjs from git ls-files (**.css, excluding lib/).\n// Regenerate after adding/removing a converted CSS file.\nexport const cssManifest = [\n${lines}\n]\n`
writeFileSync(outFile, body)
console.log(`css-manifest: wrote ${String(entries.length)} entries to ${outFile}`)
